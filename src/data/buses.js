export function getBusById(id) {
  return buses.find(b => b.id === id);
}

export function getBusStopById(id) {
  return busStops.find(s => s.id === id);
}

export function getBusesForStop(stopId) {
  const stop = busStops.find(s => s.id === stopId);
  if (!stop) return [];
  return stop.buses.map(busId => buses.find(b => b.id === busId)).filter(Boolean);
}

export function getConfidenceBadge(level) {
  switch (level) {
    case 'verified': return { label: 'Verified', color: '#10B981', icon: '🟢' };
    case 'community': return { label: 'Community Reported', color: '#F59E0B', icon: '🟡' };
    case 'demo': return { label: 'Demo Data', color: '#6B7280', icon: '⚪' };
    default: return { label: 'Needs Verification', color: '#EF4444', icon: '🔴' };
  }
}
